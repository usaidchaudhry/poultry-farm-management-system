import { Router } from 'express';
import { permission, anyPermission } from '../../middleware/auth.js';
import { body, validId } from '../../lib/validation.js';
import * as input from './validation.js';
import * as controller from './controller.js';
export const formulaRouter = Router();
formulaRouter.get('/', permission('feed-formulas.view'), controller.list);
formulaRouter.get('/ingredients', anyPermission('feed-formulas.view', 'feed-formulas.compose'), controller.ingredients);
formulaRouter.post('/', permission('feed-formulas.compose'), body(input.create), controller.create);
formulaRouter.use('/:id', validId);
formulaRouter.get('/:id', permission('feed-formulas.view'), controller.detail);
formulaRouter.patch('/:id', permission('feed-formulas.compose'), body(input.edit), controller.edit);
formulaRouter.post('/:id/preview', permission('feed-formulas.cost', 'feed-formulas.cost-view'), body(input.pricing), controller.preview);
formulaRouter.put('/:id/pricing', permission('feed-formulas.cost', 'feed-formulas.cost-view'), body(input.pricing), controller.action('pricing'));
formulaRouter.post('/:id/submit', permission('feed-formulas.submit'), body(input.action), controller.action('submit'));
formulaRouter.post('/:id/finalize', permission('feed-formulas.finalize', 'feed-formulas.cost-view'), body(input.action), controller.action('finalize'));
formulaRouter.post('/:id/return', permission('feed-formulas.return'), body(input.reasonAction), controller.action('return'));
formulaRouter.post('/:id/revise', permission('feed-formulas.compose'), body(input.revise), controller.action('revise'));
formulaRouter.post('/:id/archive', permission('feed-formulas.compose'), body(input.reasonAction), controller.action('archive'));
