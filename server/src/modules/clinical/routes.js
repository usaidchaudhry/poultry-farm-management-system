import { Router } from 'express';
import { body, validId } from '../../lib/validation.js';
import { permission } from '../../middleware/auth.js';
import { P } from '../access/catalog.js';
import { visitInput, visitEdit, prescriptionData, prescriptionEdit, reasonAction, replacementInput, outcomeInput } from './validation.js';
import * as c from './controller.js';
export const visitsRouter = Router();
visitsRouter.get('/', permission(P.CLINICAL_VIEW), c.visits);
visitsRouter.post('/', permission(P.CLINICAL_MANAGE), body(visitInput), c.createVisit);
visitsRouter.use('/:id', validId);
visitsRouter.get('/:id', permission(P.CLINICAL_VIEW), c.visit);
visitsRouter.patch('/:id', permission(P.CLINICAL_MANAGE), body(visitEdit), c.editVisit);
visitsRouter.post('/:id/schedule-preview', permission(P.CLINICAL_MANAGE), body(prescriptionData), c.preview);
visitsRouter.post('/:id/prescriptions', permission(P.CLINICAL_MANAGE), body(prescriptionData), c.createPrescription);
export const prescriptionsRouter = Router();
prescriptionsRouter.use('/:id', validId);
prescriptionsRouter.patch('/:id', permission(P.CLINICAL_MANAGE), body(prescriptionEdit), c.editPrescription);
prescriptionsRouter.post('/:id/finalize', permission(P.CLINICAL_MANAGE), body(reasonAction), c.finalize);
prescriptionsRouter.post('/:id/cancel', permission(P.CLINICAL_MANAGE), body(reasonAction), c.cancel);
prescriptionsRouter.post('/:id/replace', permission(P.CLINICAL_MANAGE), body(replacementInput), c.replace);
export const medicationRouter = Router();
medicationRouter.get('/', permission(P.MEDICATION_VIEW), c.tasks);
medicationRouter.get('/:id', permission(P.MEDICATION_VIEW), validId, c.task);
medicationRouter.post('/:id/outcomes', permission(P.MEDICATION_ADMINISTER), validId, body(outcomeInput), c.outcome);
medicationRouter.post('/:id/corrections', permission(P.MEDICATION_CORRECT), validId, body(outcomeInput), c.correct);
