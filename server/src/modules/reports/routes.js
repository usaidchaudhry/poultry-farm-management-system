import { Router } from 'express';
import { permission, anyPermission } from '../../middleware/auth.js';
import { body, validId } from '../../lib/validation.js';
import { createSchema, editSchema, actionSchema, movementInput, measurementInput } from './validation.js';
import * as controller from './controller.js';
export const reportRouter = Router();
reportRouter.get('/', permission('daily-reports.view'), controller.list);
reportRouter.post('/', permission('daily-reports.manage'), body(createSchema), controller.create);
reportRouter.use('/:id', validId);
reportRouter.get('/:id', permission('daily-reports.view'), controller.detail);
reportRouter.patch('/:id', permission('daily-reports.manage'), body(editSchema), controller.update);
reportRouter.post('/:id/submit', permission('daily-reports.submit'), body(actionSchema), controller.submit);
reportRouter.post('/:id/return', permission('daily-reports.review'), body(actionSchema), controller.returnReport);
export const populationRouter = Router();
populationRouter.use('/:id', validId);
populationRouter.get('/:id/population', anyPermission('daily-reports.view', 'bird-population.manage'), controller.population);
populationRouter.post('/:id/population-adjustments', permission('bird-population.manage'), body(movementInput), controller.movement);
export const measurementRouter = Router();
measurementRouter.get('/', permission('bird-parameters.view'), controller.measurements);
measurementRouter.post('/', permission('bird-parameters.manage'), body(measurementInput), controller.createMeasurement);
measurementRouter.get('/:id', permission('bird-parameters.view'), validId, controller.measurement);
export { controller };
