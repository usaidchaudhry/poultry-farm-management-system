import { Router } from 'express';
import { permission, anyPermission } from '../../middleware/auth.js';
import { body, validId } from '../../lib/validation.js';
import * as input from './validation.js';
import * as c from './controller.js';
export const productionRouter = Router();
productionRouter.get('/', permission('egg-production.view'), c.list('production'));
productionRouter.get('/farms/:id/policy', anyPermission('egg-production.view', 'sales.view'), validId, c.policy);
productionRouter.put('/farms/:id/policy', permission('egg-production.manage'), validId, body(input.policyInput), c.updatePolicy);
productionRouter.get('/farms/:id/stock', anyPermission('egg-production.view', 'sales.view', 'sales.manage'), validId, c.stock);
productionRouter.post('/:id/backfill', permission('egg-production.manage', 'daily-reports.review', 'reports.history.view'), validId, body(input.backfillInput), c.backfill);
export const salesRouter = Router();
salesRouter.get('/', permission('sales.view'), c.list('listSales'));
salesRouter.post('/', permission('sales.manage'), body(input.saleInput), c.createSale);
salesRouter.use('/:id', validId);
salesRouter.get('/:id', permission('sales.view'), c.sale);
salesRouter.post('/:id/payment', permission('sales.manage'), body(input.payment), c.saleAction('payment'));
salesRouter.post('/:id/dispatch', permission('sales.manage'), body(input.action), c.saleAction('dispatch'));
salesRouter.post('/:id/cancel', permission('sales.manage'), body(input.reason), c.saleAction('cancel'));
export const expensesRouter = Router();
expensesRouter.get('/', permission('finance.view'), c.list('listExpenses'));
expensesRouter.post('/', permission('finance.manage'), body(input.expenseInput), c.createExpense);
expensesRouter.use('/:id', validId);
expensesRouter.get('/:id', permission('finance.view'), c.expense);
expensesRouter.post('/:id/void', permission('finance.manage'), body(input.reason), c.expenseAction('void'));
expensesRouter.post('/:id/replace', permission('finance.manage'), body(input.replacement), c.expenseAction('replace'));
export const financeRouter = Router();
financeRouter.get('/', permission('finance.view'), c.list('finance'));
financeRouter.get('/sources', permission('finance.view'), c.list('sources'));
